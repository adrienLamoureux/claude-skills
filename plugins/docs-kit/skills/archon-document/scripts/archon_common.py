def _scalar(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def parse_frontmatter(text):
    """Parse the flat YAML subset the MD twin uses: scalars, [inline, lists] and '- item' lists.

    Returns (meta, body). A missing frontmatter yields ({}, text).
    """
    match = FRONTMATTER_RE.match(text)
    if not match:
        return {}, text
    meta, last_key = {}, None
    for raw in match.group(1).splitlines():
        line = re.sub(r"\s+#\s.*$", "", raw).rstrip()
        if not line.strip():
            continue
        item = re.match(r"^\s*-\s+(.*)$", line)
        if item and last_key:
            if not isinstance(meta.get(last_key), list):
                meta[last_key] = []
            meta[last_key].append(_scalar(item.group(1)))
            continue
        key, _, value = line.partition(":")
        last_key = key.strip()
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            meta[last_key] = [_scalar(v) for v in value[1:-1].split(",") if v.strip()]
        else:
            meta[last_key] = _scalar(value)
    return meta, text[match.end():]


def as_list(value):
    if isinstance(value, list):
        return value
    return [value] if value else []


def palette_version():
    match = PALETTE_RE.search(CSS_PATH.read_text(encoding="utf-8"))
    return match.group(1) if match else "unknown"


def extract_between(text, start, end):
    i, j = text.find(start), text.find(end)
    if i < 0 or j < i:
        return None
    return text[i + len(start):j]


def read_embedded_meta(page_html):
    match = re.search(r'<script type="application/json" id="ar-meta">(.*?)</script>', page_html, re.S)
    return json.loads(match.group(1)) if match else None


def doc_order(meta):
    """The optional `order` key as an int, or None when absent or not a number."""
    try:
        return int(meta.get("order"))
    except (TypeError, ValueError):
        return None


def doc_group(meta):
    """The optional `group` key, else the plural of the doc type's label."""
    return meta.get("group") or f"{DOC_TYPES.get(meta.get('doc_type'), 'Document')}s"


def _doc_sort_key(doc):
    meta, order = doc["meta"], doc_order(doc["meta"])
    return (order is None, order or 0, str(meta.get("doc_type", "")), str(meta.get("title", "")).lower())


def load_docs(folder):
    """Every archon MD in `folder` (one with an id and a summary), in reading order.

    Reading order is `order` ascending; docs without one follow, by doc type then title.
    The index page and every page's prev/next links share this one order.
    """
    docs = []
    for md in folder.glob("*.md"):
        if md.name == INDEX_NAME:
            continue
        meta, _ = parse_frontmatter(md.read_text(encoding="utf-8"))
        if not meta.get("id") or not meta.get("summary"):
            continue
        html_twin = folder / (meta.get("html_twin") or f"{md.stem}.html")
        docs.append({"md": md, "meta": meta, "html": html_twin})
    return sorted(docs, key=_doc_sort_key)


def group_docs(docs):
    """[(group, [docs])], groups in the order their first doc appears."""
    groups = {}
    for doc in docs:
        groups.setdefault(doc_group(doc["meta"]), []).append(doc)
    return list(groups.items())


def read_index_meta(folder):
    """The embedded meta of `folder`'s index.html if build_index.py generated it, else None."""
    path = folder / INDEX_HTML_NAME
    if not path.is_file():
        return None
    meta = read_embedded_meta(path.read_text(encoding="utf-8"))
    return meta if meta and meta.get("kind") == INDEX_KIND else None


def page_nav(md_path):
    """Collection links for one page: up to the folder's index, prev/next in reading order.

    Only docs whose HTML page exists are linked, so a half-built folder never links to a 404.
    """
    folder, nav = md_path.parent, {}
    index_meta = read_index_meta(folder)
    if index_meta:
        nav["up"] = {"href": INDEX_HTML_NAME, "title": index_meta.get("title", "Index")}
    me = md_path.resolve()
    docs = [d for d in load_docs(folder) if d["html"].is_file() or d["md"].resolve() == me]
    paths = [d["md"].resolve() for d in docs]
    if me in paths:
        i = paths.index(me)

        def link(doc):
            return {"href": doc["html"].name, "title": doc["meta"].get("title", doc["md"].stem)}

        if i > 0:
            nav["prev"] = link(docs[i - 1])
        if i < len(docs) - 1:
            nav["next"] = link(docs[i + 1])
    return nav


def strip_tags(fragment):
    return html.unescape(TAG_RE.sub(" ", fragment))


def word_count(text):
    return len(WORD_RE.findall(text))
